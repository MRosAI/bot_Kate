@dp.message()
async def message_handler(message: types.Message):

    user_id = message.from_user.id

    # Защита от спама
    if is_rate_limited(user_id):
        await message.answer(
            "⏳ Слишком много сообщений подряд.\n\n"
            "Подожди несколько секунд и продолжи 🌸"
        )
        return

    # Защита от сообщений без текста
    text = message.text.strip() if message.text else ""


    # =====================================================
    # НАЗАД
    # =====================================================

    if text == "⬅️ Назад":

        await show_tariffs(message)

        return


    # =====================================================
    # ДЛЯ СНГ
    # =====================================================

    if text == "🇷🇺 Для СНГ":

        await show_cis_payment(message)

        return


    # =====================================================
    # ДЛЯ ДРУГИХ СТРАН
    # =====================================================

    if text == "🌍 Для других стран":

        await show_international_payment(message)

        return


    # =====================================================
    # ПРАВИЛА РАБОТЫ И ОПЛАТ
    # =====================================================

    if text == "📋 Правила работы и оплат":

        await show_rules(message)

        return


    # =====================================================
    # ОТЗЫВЫ
    # =====================================================

    if text == "💬 Отзывы":

        await message.answer(
            "❤️ <b>Отзывы девушек</b>\n\n"
            "Спасибо каждой, кто поделился своими впечатлениями 🌸",
            parse_mode="HTML",
            reply_markup=reviews_keyboard
        )

        for photo_id in REVIEW_PHOTOS:
            await message.answer_photo(photo=photo_id)

        return


    # =====================================================
    # МНЕ ИНТЕРЕСНО
    # =====================================================

    if text == "Мне интересно":

        await show_tariffs(message)

        return


    # =====================================================
    # БАЗОВЫЙ ТАРИФ
    # =====================================================

    if text == "💰 Базовый расчёт — 600 ₽":

        await bot.send_invoice(
            chat_id=message.chat.id,
            title="Базовый расчёт",
            description="Персональный расчёт на 2027 и 2028 год",
            payload="basic_600",
            provider_token=PAYMENT_PROVIDER_TOKEN,
            currency="RUB",
            prices=[
                LabeledPrice(
                    label="Базовый расчёт",
                    amount=60000
                )
            ]
        )

        return


    # =====================================================
    # РАСШИРЕННЫЙ ТАРИФ
    # =====================================================

    if text == "💎 Расширенный расчёт — 1200 ₽":

        await bot.send_invoice(
            chat_id=message.chat.id,
            title="Расширенный расчёт",
            description="Расширенный персональный расчёт",
            payload="extended_1200",
            provider_token=PAYMENT_PROVIDER_TOKEN,
            currency="RUB",
            prices=[
                LabeledPrice(
                    label="Расширенный расчёт",
                    amount=120000
                )
            ]
        )

        return


    # =====================================================
    # ПРОВЕРКА ДАТЫ
    # =====================================================

    try:

        datetime.strptime(text, "%d.%m.%Y")

    except ValueError:

        await message.answer(
            "Не совсем понял дату 🌸\n\n"
            "Пожалуйста, введи её в формате:\n"
            "ДД.ММ.ГГГГ\n\n"
            "Например: 22.04.1996"
        )

        return


    # =====================================================
    # СОХРАНЯЕМ ДАТУ
    # =====================================================

    user_dates[user_id] = text


    # =====================================================
    # ПОДТВЕРЖДЕНИЕ
    # =====================================================

    await message.answer(
        f"Ты указала дату рождения:\n\n"
        f"🎂 {text}\n\n"
        f"Всё верно?",
        reply_markup=confirm_keyboard
    )


