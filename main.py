def calculate_program(date_text: str) -> int:

    date = datetime.strptime(date_text, "%d.%m.%Y")

    day = date.day
    month = date.month

    result = day + month
    result += 11

    while result > 9:
        result = sum(int(digit) for digit in str(result))

    return result


